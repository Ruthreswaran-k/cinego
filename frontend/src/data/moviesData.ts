// Helper functions for dynamic UI generation

// 1. Now Showing: status == RUNNING && bookingEnabled == true
export const getNowShowingMovies = (): Movie[] => {
  return ALL_MOVIES.filter((m) => m.status === 'RUNNING' && m.bookingEnabled);
};

// 2. Upcoming Movies: status == UPCOMING
export const getUpcomingMovies = (): Movie[] => {
  return ALL_MOVIES.filter((m) => m.status === 'UPCOMING');
};

// 3. Trending Now: sorted by popularityScore DESC
export const getTrendingMovies = (): Movie[] => {
  return [...ALL_MOVIES].sort((a, b) => b.popularityScore - a.popularityScore);
};

// 4. Top Rated: sorted by seedRating DESC
export const getTopRatedMovies = (): Movie[] => {
  return [...ALL_MOVIES].sort((a, b) => b.seedRating - a.seedRating);
};

// 5. Language / Industry Filters
export const getKollywoodMovies = (): Movie[] => {
  return ALL_MOVIES.filter((m) => m.language === 'Tamil' || m.industry === 'Kollywood');
};

export const getMollywoodMovies = (): Movie[] => {
  return ALL_MOVIES.filter((m) => m.language === 'Malayalam' || m.industry === 'Mollywood');
};

export const getHollywoodMovies = (): Movie[] => {
  return ALL_MOVIES.filter((m) => m.language === 'English' || m.industry === 'Hollywood');
};

// 6. Cold-Start Recommendation System
export interface UserPreferences {
  languages?: string[];
  genres?: string[];
}

export const getRecommendedMovies = (prefs?: UserPreferences): Movie[] => {
  return [...ALL_MOVIES]
    .map((m) => {
      let score = m.seedRating * 10 + m.popularityScore * 0.4;
      if (m.tags.includes('RECOMMENDED')) score += 15;
      if (m.tags.includes('TRENDING')) score += 10;
      if (m.bookingEnabled) score += 8;

      if (prefs?.languages && prefs.languages.length > 0) {
        if (prefs.languages.includes(m.language) || prefs.languages.includes('All')) {
          score += 20;
        }
      }

      if (prefs?.genres && prefs.genres.length > 0) {
        const hasGenre = m.genre.some((g) => prefs.genres?.includes(g));
        if (hasGenre) score += 15;
      }

      return { movie: m, score };
    })
    .sort((a, b) => b.score - a.score)
    .map((item) => item.movie);
};

// Helper to find movie by ID or Title
export const findMovieByIdOrTitle = (query: string): Movie | undefined => {
  if (!query) return undefined;
  const q = query.trim().toLowerCase();
  return ALL_MOVIES.find(
    (m) =>
      m.movieId.toLowerCase() === q ||
      m.id.toLowerCase() === q ||
      m.title.toLowerCase() === q
  );
};
